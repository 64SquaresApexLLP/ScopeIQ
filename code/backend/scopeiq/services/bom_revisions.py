"""BOM revisions of a site. Every generated BOM is a revision (REV 1, REV 2 ...), and nothing is overwritten once it has left the scoping team.

- A draft revision is refreshed by the next pipeline run. A locked one (with the service provider, agreed, approved) is never touched, so the next run
  makes the next revision. A change request or a rework therefore always ends in a new revision.
- The lines are kept per revision (CORE.BOM_OUTPUT_LINE.BOM_REV_ID), so earlier revisions stay readable.
- Each revision keeps the line-by-line difference from the one before it (CORE.BOM_CHANGE).
- Sites made before revisions were tracked have lines with no revision; `ensure` gives them REV 1.
"""
from __future__ import annotations

from scopeiq.common.ids import stable_id
from scopeiq.db.repository import Repository, now_iso

LINES = "CORE.BOM_OUTPUT_LINE"


def generated(repo: Repository, site_id: str) -> list[dict]:
    """The site's generated revisions, oldest first (REV 0, the tool's preliminary BOM, is not one of them)."""
    return [x for x in repo.select("CORE.BOM_REVISION", {"SITE_ID": site_id}, order_by="REV_NO") if x.get("KIND") != "TOOL_REV0"]


def current_revision(repo: Repository, site_id: str) -> dict | None:
    revs = generated(repo, site_id)
    return revs[-1] if revs else None


def is_draft(rev: dict | None) -> bool:
    return bool(rev and rev.get("STATUS") == "DRAFT" and not rev.get("LOCKED"))


def lines_of(repo: Repository, site_id: str, rev: dict | None) -> list[dict]:
    """The lines of one revision. Lines made before revisions were tracked belong to the site's latest revision, or to none if there is none yet."""
    rows = repo.select(LINES, {"SITE_ID": site_id}, order_by="CATEGORY, SECTOR, CATALOG_KEY")
    if rev is None:
        return [x for x in rows if not x.get("BOM_REV_ID")]
    own = [x for x in rows if x.get("BOM_REV_ID") == rev["BOM_REV_ID"]]
    if own or rev["BOM_REV_ID"] != (current_revision(repo, site_id) or {}).get("BOM_REV_ID"):
        return own
    return [x for x in rows if not x.get("BOM_REV_ID")]


def current(repo: Repository, site_id: str) -> tuple[dict | None, list[dict]]:
    """The site's current revision and its lines."""
    rev = current_revision(repo, site_id)
    return rev, lines_of(repo, site_id, rev)


def clear_draft(repo: Repository, site_id: str, user: str) -> None:
    """At the start of a run: drop the draft revision (the run rebuilds it). A revision that has left the scoping team keeps its lines and its place."""
    rev = ensure(repo, site_id, user)
    if is_draft(rev):
        repo.delete_where(LINES, {"SITE_ID": site_id, "BOM_REV_ID": rev["BOM_REV_ID"]})
        repo.delete_where("CORE.BOM_CHANGE", {"TO_REV_ID": rev["BOM_REV_ID"]})
        repo.delete_where("CORE.BOM_REVISION", {"BOM_REV_ID": rev["BOM_REV_ID"]})


def register(repo: Repository, site_id: str, run_id: str, user: str) -> dict:
    """The revision this run's BOM belongs to: the draft, refreshed, or else the next revision."""
    gen = generated(repo, site_id)
    latest = gen[-1] if gen else None
    ts = now_iso()
    if is_draft(latest):
        repo.update("CORE.BOM_REVISION", {"RUN_ID": run_id, "CREATED_AT": ts, "CREATED_BY": user}, {"BOM_REV_ID": latest["BOM_REV_ID"]})
        return repo.get("CORE.BOM_REVISION", BOM_REV_ID=latest["BOM_REV_ID"])
    rev_no = (latest["REV_NO"] + 1) if latest else 1
    row = {"BOM_REV_ID": f"{site_id}-REV{rev_no}", "SITE_ID": site_id, "REV_NO": rev_no, "REV_LABEL": f"REV {rev_no}", "KIND": "GENERATED", "STATUS": "DRAFT",
           "LOCKED": False, "RUN_ID": run_id, "PARENT_REV_ID": latest["BOM_REV_ID"] if latest else None, "CREATED_AT": ts, "CREATED_BY": user,
           "NOTES": "Generated by the BOM rules from the site's design"}
    repo.insert("CORE.BOM_REVISION", [row])
    return row


def _totals(lines: list[dict]) -> dict:
    install = [x for x in lines if str(x.get("ACTION") or "").lower() == "install"]
    remove = [x for x in lines if str(x.get("ACTION") or "").lower() == "remove"]
    return {"lines": len(lines), "install_lines": len(install), "remove_lines": len(remove),
            "total_cost_usd": round(sum(float(x.get("TOTAL_COST_USD") or 0) for x in install), 2)}


def finish(repo: Repository, site_id: str, rev: dict) -> list[dict]:
    """After the lines are written: the revision's totals, and its differences from the revision before."""
    lines = lines_of(repo, site_id, rev)
    repo.update("CORE.BOM_REVISION", {"TOTALS": _totals(lines)}, {"BOM_REV_ID": rev["BOM_REV_ID"]})
    return record_changes(repo, site_id, rev)


def record_changes(repo: Repository, site_id: str, rev: dict) -> list[dict]:
    """The line-by-line difference of a revision from the one before it: what was added, removed or changed in quantity."""
    repo.delete_where("CORE.BOM_CHANGE", {"TO_REV_ID": rev["BOM_REV_ID"]})
    prev = next((x for x in reversed(generated(repo, site_id)) if x["REV_NO"] < rev["REV_NO"]), None)
    if not prev:
        return []
    key = lambda x: (x.get("SECTOR") or "SITE", x.get("CATALOG_KEY") or x.get("MODEL") or "", x.get("ACTION") or "")   # noqa: E731

    def by_key(lines):
        out: dict = {}
        for x in lines:
            o = out.setdefault(key(x), {"qty": 0.0, "reasons": set()})
            o["qty"] += float(x.get("TOTAL_QTY") or 0)
            if x.get("REASON_CODE"):
                o["reasons"].add(x["REASON_CODE"])
        return out

    before, after = by_key(lines_of(repo, site_id, prev)), by_key(lines_of(repo, site_id, rev))
    for gone in (repo.get("CORE.BOM_REVISION", BOM_REV_ID=rev["BOM_REV_ID"]).get("REMOVALS") or []):      # a removed line has no row left to carry its reason
        k = (gone.get("sector") or "SITE", gone.get("catalog_key") or "", gone.get("action") or "")
        if k in before:
            before[k]["reasons"].add(gone["reason"])
    rows = []
    for k in sorted(set(before) | set(after)):
        a, b = before.get(k, {"qty": 0.0, "reasons": set()}), after.get(k, {"qty": 0.0, "reasons": set()})
        if a["qty"] != b["qty"]:
            rows.append({"CHANGE_ID": stable_id("CHG", rev["BOM_REV_ID"], len(rows)), "SITE_ID": site_id, "FROM_REV_ID": prev["BOM_REV_ID"], "TO_REV_ID": rev["BOM_REV_ID"],
                         "SECTOR": k[0], "CATALOG_KEY": k[1], "ACTION": k[2], "FROM_QTY": a["qty"], "TO_QTY": b["qty"], "DELTA": b["qty"] - a["qty"],
                         "REASONS": sorted(a["reasons"] | b["reasons"])})
    if rows:
        repo.insert("CORE.BOM_CHANGE", rows)
    return rows


# the revision status that matches where the site is in the handshake, for a site made before revisions followed the site
_STATUS_OF_SITE = {"SP_HANDSHAKE": "SP_REVIEW", "SUBMITTED_FBA": "SP_AGREED", "FBA_APPROVED": "FBA"}


def ensure(repo: Repository, site_id: str, user: str) -> dict | None:
    """A site made before revisions were tracked has BOM lines but no revision: give it REV 1, in the state that matches where the site is."""
    rev = current_revision(repo, site_id)
    if rev:
        return rev
    if not lines_of(repo, site_id, None):
        return None
    site = (repo.select("CORE.SITE", {"SITE_ID": site_id}, limit=1) or [{}])[0]
    status = _STATUS_OF_SITE.get(site.get("WORKFLOW_STATE") or "", "DRAFT")
    row = {"BOM_REV_ID": f"{site_id}-REV1", "SITE_ID": site_id, "REV_NO": 1, "REV_LABEL": "REV 1", "KIND": "GENERATED", "STATUS": status, "LOCKED": status != "DRAFT",
           "RUN_ID": site.get("LAST_RUN_ID"), "PARENT_REV_ID": None, "CREATED_AT": now_iso(), "CREATED_BY": user, "NOTES": "Generated by the BOM rules from the site's design"}
    repo.insert("CORE.BOM_REVISION", [row])
    repo.execute(f"UPDATE {LINES} SET BOM_REV_ID = %s WHERE SITE_ID = %s AND BOM_REV_ID IS NULL", [row["BOM_REV_ID"], site_id])
    repo.update("CORE.BOM_REVISION", {"TOTALS": _totals(lines_of(repo, site_id, row))}, {"BOM_REV_ID": row["BOM_REV_ID"]})
    return repo.get("CORE.BOM_REVISION", BOM_REV_ID=row["BOM_REV_ID"])


def start_next(repo: Repository, site_id: str, user: str, run_id: str | None = None) -> dict:
    """The next revision, started from the lines of the current one, so the scoping team can change it with a reason. Only when the current one is locked."""
    cur = ensure(repo, site_id, user)
    if cur is None:
        raise ValueError("There is no BOM to start a new revision from")
    if is_draft(cur):
        return cur
    rev_no = cur["REV_NO"] + 1
    rev_id = f"{site_id}-REV{rev_no}"
    row = {"BOM_REV_ID": rev_id, "SITE_ID": site_id, "REV_NO": rev_no, "REV_LABEL": f"REV {rev_no}", "KIND": "GENERATED", "STATUS": "DRAFT", "LOCKED": False,
           "RUN_ID": run_id or cur.get("RUN_ID"), "PARENT_REV_ID": cur["BOM_REV_ID"], "CREATED_AT": now_iso(), "CREATED_BY": user,
           "NOTES": f"Started from {cur['REV_LABEL']}"}
    repo.insert("CORE.BOM_REVISION", [row])
    ts = now_iso()
    copy = [{**x, "LINE_ID": stable_id("BOM", rev_id, i), "BOM_REV_ID": rev_id, "REASON_CODE": None, "EDITED_BY": None, "EDITED_AT": None, "CREATED_AT": ts}
            for i, x in enumerate(lines_of(repo, site_id, cur))]
    if copy:
        repo.insert(LINES, copy)
    finish(repo, site_id, row)
    return repo.get("CORE.BOM_REVISION", BOM_REV_ID=rev_id)


def note_removal(repo: Repository, rev: dict, line: dict, reason: str) -> None:
    """Keep why a line was taken out of a draft: the line itself is gone, so the reason is kept on the revision for its difference list."""
    row = repo.get("CORE.BOM_REVISION", BOM_REV_ID=rev["BOM_REV_ID"])
    repo.update("CORE.BOM_REVISION", {"REMOVALS": [*(row.get("REMOVALS") or []), {"sector": line.get("SECTOR"), "catalog_key": line.get("CATALOG_KEY") or line.get("MODEL"),
                                                                                  "action": line.get("ACTION"), "reason": reason}]}, {"BOM_REV_ID": rev["BOM_REV_ID"]})


def scope_items(repo: Repository, site_id: str, run_id: str | None = None) -> list[dict]:
    """The scope of work of a site: the equipment to install, remove or keep, by sector. It is the delta of the run when there is one, else the design read in stage 5."""
    delta = repo.select("CORE.EQUIPMENT_DELTA", {"SITE_ID": site_id, "RUN_ID": run_id}, order_by="SEQ") if run_id else []
    if delta:
        return delta
    items = repo.select("CORE.DESIGN_ITEM", {"SITE_ID": site_id}, order_by="SECTOR, POSITION")
    return [{"SEQ": i, "SECTOR": x.get("SECTOR"), "POSITION": x.get("POSITION"), "KIND": x.get("KIND"), "CATALOG_KEY": x.get("MODEL") or x.get("CATALOG_KEY"),
             "DESCRIPTION": x.get("DESCRIPTION"), "ACTION": x.get("ACTION"), "BASIS": x.get("SOURCE")} for i, x in enumerate(items)]
